/**
 * Packs the Sabura skill's runtime files into plugin/skills/sabura/:
 *   scripts/sabura-board.mjs  bin/sabura-board.js and the editor modules it
 *                             uses, as one dependency-free ES module
 *   sabura.html               the editor, used as the template for new boards
 *
 * Installed plugins are copied away from this repo, so the skill folder must
 * hold everything it runs. Both files are generated: edit src/ or bin/, then
 * run `npm run plugin:build`. `--check` fails if the committed files are stale.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const skillDir = path.join(rootDir, 'plugin', 'skills', 'sabura');

// Dependency order; each module may only use names declared above it at load time.
const MODULES = [
  'src/core/types.js',
  'src/core/markup.js',
  'src/core/color.js',
  'src/core/theme-colors.js',
  'src/core/geometry.js',
  'src/core/revision.js',
  'src/core/document.js',
  'src/core/commands.js',
  'src/core/json-schema.js',
  'src/storage/file-packer.js',
  'src/agent-api.js',
  'src/board-file.js',
  'bin/sabura-board.js',
];

const IMPORT = /^import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"];?/gm;
const RE_EXPORT = /^export\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"];?/gm;
const EXPORT_LIST = /^export\s*\{([^}]*)\};?/gm;
const EXPORT_DECL = /^export\s+(?:const|let|var|function|async function|class)\s+([A-Za-z_$][\w$]*)/gm;

const names = (list) => list.split(',').map((s) => s.trim()).filter(Boolean);
const varName = (rel) => '__' + rel.replace(/\.js$/, '').replace(/[^\w]/g, '_');

/**
 * Each module runs in its own function scope (modules may share private
 * helper names) and returns its exports; relative imports become
 * destructuring from earlier modules. Node built-in imports are hoisted.
 * Supports only the forms the editor uses: named imports and exports.
 */
export function bundleBoardCli() {
  const builtins = new Set();
  const blocks = MODULES.map((rel) => {
    let code = fs.readFileSync(path.join(rootDir, rel), 'utf8').replace(/^#!.*\n/, '');
    const dir = path.posix.dirname(rel);
    const target = (spec) => {
      const resolved = path.posix.normalize(path.posix.join(dir, spec));
      if (!MODULES.includes(resolved)) throw new Error(`${rel}: ${spec} is not in the plugin bundle`);
      if (MODULES.indexOf(resolved) >= MODULES.indexOf(rel)) throw new Error(`${rel}: ${spec} must come earlier in MODULES`);
      return varName(resolved);
    };
    const exported = [];

    code = code.replace(RE_EXPORT, (_, list, spec) => {
      exported.push(...names(list));
      return `const { ${names(list).join(', ')} } = ${target(spec)};`;
    });
    code = code.replace(IMPORT, (whole, list, spec) => {
      if (!spec.startsWith('.')) {
        builtins.add(whole.trim().replace(/;?$/, ';'));
        return '';
      }
      if (/\bas\b/.test(list)) throw new Error(`${rel}: renamed imports are not supported`);
      return `const { ${names(list).join(', ')} } = ${target(spec)};`;
    });
    code = code.replace(EXPORT_LIST, (_, list) => {
      exported.push(...names(list));
      return '';
    });
    code = code.replace(EXPORT_DECL, (whole, name) => {
      exported.push(name);
      return whole.replace(/^export\s+/, '');
    });
    if (/^(import|export)\s/m.test(code)) throw new Error(`${rel}: unsupported import/export form`);

    const unique = [...new Set(exported)];
    return `// --- ${rel} ---\nconst ${varName(rel)} = (() => {\n${code.trim()}\nreturn { ${unique.join(', ')} };\n})();\n`;
  });
  return '#!/usr/bin/env node\n'
    + '// Generated by scripts/build-plugin.js from the Sabura editor sources. Do not edit.\n'
    + '// Source: https://github.com/sabura-app/sabura-editor (MIT)\n'
    + [...builtins].sort().join('\n') + '\n\n'
    + blocks.join('\n');
}

export function pluginFiles() {
  return {
    [path.join(skillDir, 'scripts', 'sabura-board.mjs')]: bundleBoardCli(),
    [path.join(skillDir, 'sabura.html')]: fs.readFileSync(path.join(rootDir, 'sabura.html'), 'utf8'),
  };
}

function main() {
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [file, content] of Object.entries(pluginFiles())) {
    const rel = path.relative(rootDir, file);
    if (check) {
      const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
      if (current !== content) stale.push(rel);
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content);
      if (file.endsWith('.mjs')) fs.chmodSync(file, 0o755);
      console.log(`wrote ${rel} (${Buffer.byteLength(content).toLocaleString()} bytes)`);
    }
  }
  if (stale.length) {
    console.error(`Plugin files are stale: ${stale.join(', ')}. Run npm run plugin:build.`);
    process.exitCode = 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
